/**
 * Step-by-step planner questions for each plan type, and the detailed item lists they produce.
 *
 * A wizard asks one question per screen (counts, a single choice, picture tiles, what the customer
 * already has, quality, budget, date). Each item says when it applies (`when`: any of these answers
 * picked; `needs`: this count is above zero) and how its quantity grows with the answers
 * (`fixed + Σ per[answer] × value`, then × each `times` answer). Prices are rough naira estimates
 * for BASIC, STANDARD and PREMIUM; listings always show the seller's live price.
 */
import type { Priority, Tier } from './planner-templates.js';

export interface WizardOption {
  id: string;
  label: string;
  icon: string;
  hint?: string;
  /** A number this choice stands for (weeks of shopping, bedrooms…), used in quantities. */
  value?: number;
}
export interface WizardCounter {
  id: string;
  label: string;
  icon: string;
  hint?: string;
  min: number;
  max: number;
  default: number;
}
export type WizardStep =
  | { id: string; type: 'counts'; title: string; hint?: string; counters: WizardCounter[] }
  | {
      id: string;
      type: 'single' | 'multi' | 'chips';
      title: string;
      hint?: string;
      options: WizardOption[];
      default?: string | string[];
    }
  | { id: string; type: 'days'; title: string; hint?: string; default?: string[] }
  | { id: 'have'; type: 'have'; title: string; hint?: string }
  | { id: 'quality'; type: 'quality'; title: string; hint?: string }
  | { id: 'budget'; type: 'budget'; title: string; hint?: string }
  | { id: 'target_date'; type: 'date'; title: string; hint?: string };

export interface WizardItem {
  section: string;
  icon: string;
  name: string;
  category: string;
  keywords: string;
  unit: string;
  qty: { fixed?: number; per?: Record<string, number>; times?: string[] };
  price: [number, number, number];
  priority: Priority;
  /** Included only when any of these answers is picked. */
  when?: string[];
  /** Left out when any of these answers is picked. */
  unless?: string[];
  /** Included only when this count is above zero. */
  needs?: string;
}
export interface Wizard {
  template: string;
  /** Which counts fill the plan's people and rooms columns. */
  people?: string[];
  rooms?: string;
  steps: WizardStep[];
  /** Meal plans pick recipes instead of a fixed list. */
  meals?: boolean;
  /** Days before the target date to buy each section (the rest use `leadDefault`). */
  lead?: Record<string, number>;
  leadDefault?: number;
  items: WizardItem[];
}
export type Answers = Record<string, number | string | string[]>;

