// ---------- answers ----------
const optionSteps = (w: Wizard) =>
  w.steps.filter(
    (s): s is Extract<WizardStep, { options: WizardOption[] }> =>
      s.type === 'single' || s.type === 'multi' || s.type === 'chips',
  );
const counters = (w: Wizard) => w.steps.flatMap((s) => (s.type === 'counts' ? s.counters : []));

/** Fills defaults and drops anything that isn't one of the wizard's own answers. */
export function cleanAnswers(w: Wizard, raw: Answers = {}): Answers {
  const out: Answers = {};
  for (const c of counters(w)) {
    const v = Number(raw[c.id]);
    out[c.id] = Number.isFinite(v) ? Math.min(c.max, Math.max(c.min, Math.round(v))) : c.default;
  }
  for (const s of optionSteps(w)) {
    const ids = new Set(s.options.map((o) => o.id));
    if (s.type === 'single') {
      const v = raw[s.id];
      out[s.id] = typeof v === 'string' && ids.has(v) ? v : String(s.default ?? s.options[0].id);
    } else {
      const v = raw[s.id];
      out[s.id] = Array.isArray(v)
        ? v.filter((x) => ids.has(x))
        : ((s.default as string[] | undefined) ?? []);
    }
  }
  for (const s of w.steps)
    if (s.type === 'days') {
      const v = raw[s.id];
      const all = ['MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT', 'SUN'];
      out[s.id] = Array.isArray(v) ? all.filter((d) => v.includes(d)) : (s.default ?? all);
    }
  if (Array.isArray(raw.have)) out.have = raw.have.map(String).slice(0, 200);
  else out.have = [];
  if (w.steps.some((s) => s.type === 'quality'))
    out.quality = (tiers as string[]).includes(String(raw.quality))
      ? String(raw.quality)
      : 'STANDARD';
  return out;
}

/** Every option picked in single, multi and chip steps. */
export function picked(w: Wizard, a: Answers) {
  const set = new Set<string>();
  for (const s of optionSteps(w)) {
    const v = a[s.id];
    if (typeof v === 'string') set.add(v);
    else if (Array.isArray(v)) v.forEach((x) => set.add(x));
  }
  return set;
}

/** The number an answer stands for in quantities: a count, a choice's value or how many picked. */
export function answerValue(w: Wizard, a: Answers, key: string): number {
  const v = a[key];
  if (typeof v === 'number') return v;
  const step = optionSteps(w).find((s) => s.id === key);
  if (typeof v === 'string') return step?.options.find((o) => o.id === v)?.value ?? 1;
  if (Array.isArray(v)) return v.length;
  return 0;
}

export function peopleOf(w: Wizard, a: Answers) {
  return w.people?.reduce((sum, k) => sum + answerValue(w, a, k), 0) || null;
}
export function roomsOf(w: Wizard, a: Answers) {
  return w.rooms ? Math.max(1, answerValue(w, a, w.rooms)) : null;
}

export interface WizardLine {
  section: string;
  icon: string;
  name: string;
  category: string;
  keywords: string;
  unit: string;
  quantity: number;
  price: [number, number, number];
  tier: number;
  budget_kobo: number;
  priority: Priority;
  position: number;
}

/** Items that apply to these answers (before "already have"), with quantities worked out. */
export function applicableItems(w: Wizard, a: Answers, tier: Tier): WizardLine[] {
  const on = picked(w, a);
  const lines: WizardLine[] = [];
  w.items.forEach((item, position) => {
    if (item.when?.length && !item.when.some((x) => on.has(x))) return;
    if (item.unless?.some((x) => on.has(x))) return;
    if (item.needs && !(answerValue(w, a, item.needs) > 0)) return;
    let raw = item.qty.fixed || 0;
    for (const [k, per] of Object.entries(item.qty.per || {})) raw += per * answerValue(w, a, k);
    for (const k of item.qty.times || []) raw *= answerValue(w, a, k) || 1;
    if (raw <= 0) return;
    // Weights and volumes go to the nearest half; everything else is whole.
    const step = ['kg', 'litre'].includes(item.unit) ? 0.5 : 1;
    const quantity = Math.max(step, Math.ceil(raw / step - 1e-9) * step);
    const t = tierIndex[tier];
    lines.push({
      section: item.section,
      icon: item.icon,
      name: item.name,
      category: item.category,
      keywords: item.keywords,
      unit: item.unit,
      quantity,
      price: item.price,
      tier: t,
      budget_kobo: quantity * item.price[t] * 100,
      priority: item.priority,
      position,
    });
  });
  return lines;
}

export interface FitResult {
  lines: WizardLine[];
  total_kobo: number;
  /** Total at the chosen quality before any trimming. */
  full_kobo: number;
  /** Plain-language notes on what was changed to fit the budget. */
  changes: string[];
  dropped: string[];
  fits: boolean;
}

/**
 * Fits the list inside the budget the way a careful shopper would: first cheaper versions of
 * optional and important items, then leave out optional items, then cheaper versions of essentials.
 * Essentials are never removed; if it still doesn't fit, the shortfall is reported.
 */
export function fitBudget(lines: WizardLine[], budgetKobo: number | null): FitResult {
  const cost = (l: WizardLine) => l.quantity * l.price[l.tier] * 100;
  const total = (ls: WizardLine[]) => ls.reduce((s, l) => s + cost(l), 0);
  const full = total(lines);
  let work = lines.map((l) => ({ ...l }));
  const changes: string[] = [];
  const dropped: string[] = [];
  if (budgetKobo && total(work) > budgetKobo) {
    const downgrade = (priority: Priority) => {
      const changed = new Set<WizardLine>();
      // Biggest savings first.
      const saving = (l: WizardLine) => cost(l) - l.quantity * l.price[l.tier - 1] * 100;
      const order = work
        .filter((l) => l.priority === priority && l.tier > 0)
        .sort((x, y) => saving(y) - saving(x));
      for (const l of order) {
        if (total(work) <= budgetKobo) break;
        while (l.tier > 0 && total(work) > budgetKobo) {
          l.tier--;
          changed.add(l);
        }
      }
      return changed.size;
    };
    const cheaperOptional = downgrade('OPTIONAL') + downgrade('IMPORTANT');
    if (cheaperOptional)
      changes.push(`Chose cheaper options for ${cheaperOptional} nice-to-have items`);
    if (total(work) > budgetKobo) {
      const optional = work
        .filter((l) => l.priority === 'OPTIONAL')
        .sort((x, y) => cost(y) - cost(x));
      for (const l of optional) {
        if (total(work) <= budgetKobo) break;
        work = work.filter((x) => x !== l);
        dropped.push(l.name);
      }
      if (dropped.length)
        changes.push(`Left out ${dropped.length} optional items (you can add them back)`);
    }
    if (total(work) > budgetKobo) {
      const n = downgrade('ESSENTIAL');
      if (n) changes.push(`Picked budget versions of ${n} essentials`);
    }
  }
  work.forEach((l) => (l.budget_kobo = cost(l)));
  const t = total(work);
  return {
    lines: work,
    total_kobo: t,
    full_kobo: full,
    changes,
    dropped,
    fits: !budgetKobo || t <= budgetKobo,
  };
}

export const tierOf = (a: Answers): Tier => {
  const q = String(a.quality || '').toUpperCase();
  return (tiers as string[]).includes(q) ? (q as Tier) : 'STANDARD';
};

/** The date to buy an item: the target date minus the section's lead time, never in the past. */
export function buyBy(w: Wizard | undefined, section: string, target: string | Date | null) {
  if (!w?.lead || !target) return null;
  const days = w.lead[section] ?? w.leadDefault ?? 7;
  const t = new Date(typeof target === 'string' ? `${target}T00:00:00Z` : target);
  const due = new Date(t.getTime() - days * 86400000);
  const today = new Date(new Date().toISOString().slice(0, 10) + 'T00:00:00Z');
  return (due < today ? today : due).toISOString().slice(0, 10);
}

/**
 * Turns a typed request ("wedding for 300 guests, traditional and white, ₦8m") into wizard
 * answers, so the steps open already filled in.
 */
export function answersFromRequest(
  template: string,
  read: { rooms: number | null; people: number | null },
  text: string,
): Answers {
  const t = text.toLowerCase();
  const a: Answers = {};
  const people = read.people ?? undefined;
  const set = (k: string, v: number | undefined) => v != null && (a[k] = v);
  switch (template) {
    case 'home-setup':
      set('bedrooms', read.rooms ?? undefined);
      set('people', people);
      if (/self.?con/.test(t)) a.bedrooms = 0;
      break;
    case 'groceries':
    case 'meal-plan':
    case 'household':
      set('adults', people);
      break;
    case 'kitchen-utensils':
      set('people', people);
      break;
    case 'wedding': {
      set('guests', people);
      const c = [
        [/trad|traditional|introduction|engagement/, 'trad'],
        [/white|church/, 'white'],
        [/court|registry/, 'court'],
        [/reception/, 'reception'],
      ]
        .filter(([re]) => (re as RegExp).test(t))
        .map(([, id]) => id as string);
      if (c.length) a.ceremonies = c;
      break;
    }
    case 'party': {
      set('guests', people);
      const o = (
        [
          [/birthday/, 'birthday'],
          [/naming|christening/, 'naming'],
          [/house ?warming/, 'housewarming'],
          [/graduat|convocation/, 'graduation'],
          [/office|end of year|staff/, 'office'],
          [/burial|funeral|remembrance/, 'remembrance'],
        ] as const
      ).find(([re]) => re.test(t));
      if (o) a.occasion = o[1];
      break;
    }
    case 'office-setup':
      set('staff', people);
      if (/\bshop|store\b/.test(t)) a.space = 'shop';
      if (/salon|barb|studio/.test(t)) a.space = 'salon';
      break;
    case 'back-to-school':
      if (/boarding/.test(t)) a.boarding = 'boarding';
      break;
  }
  return a;
}
