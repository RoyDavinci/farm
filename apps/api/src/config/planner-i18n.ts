const dictionaries: Record<string, Dict> = { pcm, yo, ha, ig };

/** The steps with titles and hints in the chosen language (English where not translated). */
export function translateSteps(steps: WizardStep[], lang: string): WizardStep[] {
  const d = dictionaries[lang];
  if (!d) return steps;
  return steps.map((s) => ({
    ...s,
    title: d[s.title] ?? s.title,
    ...(s.hint ? { hint: d[s.hint] ?? s.hint } : {}),
  }));
}
