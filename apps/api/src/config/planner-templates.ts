/**
 * Smart Planner templates (no AI). Each template is a checklist with quantity rules and price
 * estimates per quality tier, in naira. Estimates are only for budgeting: listings always show the
 * seller's live price. Edit freely; plans keep their own copy of each item once created.
 */
export type PlanKind = 'HOME' | 'EVENT' | 'FOOD' | 'PERSONAL' | 'OFFICE' | 'CUSTOM';
export type Tier = 'BASIC' | 'STANDARD' | 'PREMIUM';
export type Priority = 'ESSENTIAL' | 'IMPORTANT' | 'OPTIONAL';
export type Question = 'budget' | 'people' | 'rooms' | 'tier' | 'target_date';

export interface TemplateItem {
  section: string;
  name: string;
  /** Catalogue category used to find products. */
  category: string;
  /** Search words matched against listing titles and descriptions. */
  keywords: string;
  unit: string;
  /** Quantity = fixed + perRoom × rooms + perPerson × people, rounded up. */
  qty: { fixed?: number; perRoom?: number; perPerson?: number };
  /** Estimated unit price in naira for BASIC, STANDARD and PREMIUM. */
  price: [number, number, number];
  priority: Priority;
}
export interface PlanTemplate {
  key: string;
  kind: PlanKind;
  title: string;
  description: string;
  /** What the guided form asks. `rooms` and `people` use these labels. */
  questions: Question[];
  roomsLabel?: string;
  peopleLabel?: string;
  /** Words that point a free-text request at this template. */
  match: string[];
  items: TemplateItem[];
}

