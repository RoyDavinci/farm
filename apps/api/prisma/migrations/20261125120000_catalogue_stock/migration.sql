-- Shared product catalogue: sellers pick standard products and set a price instead of photographing
-- and describing everything. Photos are shared between sellers (with their permission) or added
-- by staff, and spread across listings so no single photo shows up everywhere.
CREATE TABLE catalogue_products (
  id text PRIMARY KEY,
  name text NOT NULL,
  brand text NOT NULL DEFAULT '',
  category text NOT NULL,
  unit text NOT NULL,
  keywords text NOT NULL DEFAULT '',
  active boolean NOT NULL DEFAULT true,
  created_by text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX catalogue_products_name_idx ON catalogue_products(lower(name), unit);
CREATE INDEX catalogue_products_category_idx ON catalogue_products(category) WHERE active;

CREATE TABLE catalogue_photos (
  id text PRIMARY KEY,
  product_id text NOT NULL REFERENCES catalogue_products(id),
  url text NOT NULL,
  thumbnail_url text,
  contributor_id text REFERENCES users(id),
  source text NOT NULL CHECK (source IN ('SELLER','STAFF')),
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (product_id, url)
);
CREATE INDEX catalogue_photos_product_idx ON catalogue_photos(product_id) WHERE active;

ALTER TABLE listings ADD COLUMN catalogue_product_id text REFERENCES catalogue_products(id);
-- The shared photo a listing shows (when the seller didn't add their own).
ALTER TABLE listings ADD COLUMN catalogue_photo_id text REFERENCES catalogue_photos(id);
-- COUNTED: the seller keeps a stock count. ALWAYS: always available; the seller confirms each order.
ALTER TABLE listings ADD COLUMN stock_mode text NOT NULL DEFAULT 'COUNTED' CHECK (stock_mode IN ('COUNTED','ALWAYS'));
-- "Out today": hidden from buyers until this time.
ALTER TABLE listings ADD COLUMN out_until timestamptz;
CREATE INDEX listings_catalogue_idx ON listings(catalogue_product_id) WHERE catalogue_product_id IS NOT NULL;

-- Always-in-stock options never run down, whatever path changes the count.
CREATE FUNCTION keep_always_in_stock() RETURNS trigger AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM listings WHERE id = NEW.listing_id AND stock_mode = 'ALWAYS') THEN
    NEW.stock := 100000;
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;
CREATE TRIGGER listing_variants_always_in_stock BEFORE INSERT OR UPDATE OF stock ON listing_variants
  FOR EACH ROW EXECUTE FUNCTION keep_always_in_stock();

-- Why a seller declined, and how reliably each seller fulfils orders (refreshed hourly).
ALTER TABLE bookings ADD COLUMN decline_reason text;
ALTER TABLE sellers ADD COLUMN fulfilment_pct integer;
ALTER TABLE sellers ADD COLUMN fulfilment_orders integer NOT NULL DEFAULT 0;

